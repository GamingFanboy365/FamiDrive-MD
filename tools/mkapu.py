#!/usr/bin/env python3
# ======================================================================
# mkapu: lookup tables for emu/apu.asm
#
# usage: mkapu.py > emu/apu_tables.asm
# ======================================================================

import math

NES_CPU = 1789773			# NTSC 2A03 clock
PSG_CLOCK = 3579545			# NTSC MD PSG clock
FM_RATE = 7670453 / 144			# NTSC YM2612 sample rate

# Length counter load values, indexed by $4003 bits 7-3
LENGTH = (10, 254, 20, 2, 40, 4, 80, 6, 160, 8, 60, 10, 14, 12, 26, 14,
	  12, 16, 24, 18, 48, 20, 96, 22, 192, 24, 72, 26, 16, 28, 32, 30)

# Noise timer periods in CPU cycles, indexed by $400E bits 3-0
NOISE = (4, 8, 16, 32, 64, 96, 128, 160, 202, 254, 380, 508, 762, 1016, 2034, 4068)


def psg_attenuation(vol):
	"""NES volume 0-15 (linear) -> PSG attenuation 0-15 (2 dB steps)."""
	if vol == 0:
		return 15
	return min(14, round(-20 * math.log10(vol / 15) / 2))


def noise_period(cycles, periodic):
	"""NES noise timer -> PSG tone 3 period N.

	With NF=3 the PSG shifts its noise register at PSG_CLOCK / (32 N);
	the NES shifts at NES_CPU / cycles. In periodic mode the PSG repeats
	every 16 shifts and the NES short mode every 93, so scale to match
	the pitch."""
	n = cycles * PSG_CLOCK / (32 * NES_CPU)
	if periodic:
		n = n * 93 / 16
	return max(1, min(1023, round(n)))


def fm_freq(period):
	"""Triangle timer period -> YM2612 $A4/$A0 value (block << 11 | fnum)."""
	f = NES_CPU / (32 * (period + 1))
	for block in range(8):
		fnum = round(f * 2 ** 20 / (FM_RATE * 2 ** (block - 1)))
		if fnum <= 2047:
			return block << 11 | fnum
	return 7 << 11 | 2047


def rows(values, fmt, per_line):
	for i in range(0, len(values), per_line):
		yield ",".join(fmt % v for v in values[i:i + per_line])


if __name__ == "__main__":
	print("; generated by tools/mkapu.py")
	print()
	print("; length counter loads, indexed by $4003 bits 7-3")
	print("apuLengthTbl:")
	for r in rows(LENGTH, "%d", 16):
		print("\t\tdc.b " + r)
	print()
	print("; NES volume 0-15 -> PSG attenuation")
	print("apuAttTbl:")
	print("\t\tdc.b " + ",".join("%d" % psg_attenuation(v) for v in range(16)))
	print()
	print("; extra attenuation for each pulse duty (12.5%, 25%, 50%, 75%):")
	print("; a 50% square is all the PSG can play, and thinner pulses are quieter")
	print("apuDutyAttTbl:")
	print("\t\tdc.b 2,1,0,1")
	print("\t\talign 2")
	print()
	print("; noise period -> PSG tone 3 period: 16 white noise, 16 periodic")
	print("apuNoiseTbl:")
	vals = [noise_period(c, False) for c in NOISE] + [noise_period(c, True) for c in NOISE]
	for r in rows(vals, "%d", 16):
		print("\t\tdc.w " + r)
	print()
	print("; triangle period $000-$7FF -> YM2612 block/fnum ($A4 high, $A0 low)")
	print("apuFmTbl:")
	for r in rows([fm_freq(p) for p in range(2048)], "$%04X", 16):
		print("\t\tdc.w " + r)
