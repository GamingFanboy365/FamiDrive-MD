#!/usr/bin/env python3
# ======================================================================
# mkpalette: NES palette -> Mega Drive colors for ppuVdpColors
#
# usage: mkpalette.py > table.asm
#
# Each NES color is matched to the Mega Drive color (of all 512) that
# looks closest: the smallest color difference in CIELAB. Matching each
# channel on its own loses the tint of pale colors (light cyan came out
# lavender). The MD's DAC isn't linear, but most emulators (and clone
# consoles) output linear levels, so the difference is summed over both:
# HW_LEVELS (measured on real hardware) and LINEAR_LEVELS.
# ======================================================================

# 2C02 palette (as rendered by Nestopia), $00-$3F
NES = """
666666 002A88 1412A7 3B00A4 5C007E 6E0040 6C0700 561D00
333500 0C4800 005200 004F08 00404D 000000 000000 000000
ADADAD 155FD9 4240FF 7527FE A01ACC B71E7B B53120 994E00
6B6D00 388700 0D9300 008F32 007C8D 000000 000000 000000
FFFFFF 64B0FF 9290FF C676FF F26AFF FF6ECC FF8170 EA9E22
BCBE00 88D800 5CE430 45E082 48CDDE 4F4F4F 000000 000000
FFFFFF C0DFFF D3D2FF E8C8FF FAC2FF FFC4EA FFCCC5 F7D8A5
E4E594 CFEF96 BDF4AB B3F3CC B5EBF2 B8B8B8 000000 000000
""".split()

HW_LEVELS = (0, 52, 87, 116, 144, 172, 206, 255)
LINEAR_LEVELS = tuple(k * 34 for k in range(8))


def lab(rgb):
	"""sRGB (0-255) -> CIELAB (D65)"""
	def lin(c):
		c /= 255
		return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
	r, g, b = (lin(c) for c in rgb)
	x = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047
	y = 0.2126 * r + 0.7152 * g + 0.0722 * b
	z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883
	f = lambda t: t ** (1 / 3) if t > 0.008856 else 7.787 * t + 16 / 116
	return 116 * f(y) - 16, 500 * (f(x) - f(y)), 200 * (f(y) - f(z))


def diff(a, b):
	return sum((p - q) ** 2 for p, q in zip(a, b)) ** 0.5


MD_COLORS = [(r, g, b) for r in range(8) for g in range(8) for b in range(8)]
MD_LAB = [(c, lab([HW_LEVELS[k] for k in c]), lab([LINEAR_LEVELS[k] for k in c])) for c in MD_COLORS]


def md_color(rgb):
	t = lab([int(rgb[i:i + 2], 16) for i in (0, 2, 4)])
	(r, g, b), _, _ = min(MD_LAB, key=lambda m: diff(m[1], t) + diff(m[2], t))
	return b << 9 | g << 5 | r << 1


if __name__ == "__main__":
	assert len(NES) == 64
	print("; generated by tools/mkpalette.py")
	for row in range(0, 64, 8):
		vals = ",".join("$%03X" % md_color(c) for c in NES[row:row + 8])
		print("\t\tdc.w %s\t; $%02X-$%02X" % (vals, row, row + 7))
