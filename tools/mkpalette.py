#!/usr/bin/env python3
# ======================================================================
# mkpalette: NES palette -> Mega Drive colors for ppuVdpColors
#
# usage: mkpalette.py > table.asm
#
# Each NES color is matched per channel to a Mega Drive level. The MD's
# DAC isn't linear, but most emulators (and clone consoles) output linear
# levels, so the level is picked to be close on both: the one with the
# smallest summed error against HW_LEVELS (measured on real hardware)
# and LINEAR_LEVELS.
# ======================================================================

# 2C02 palette (as rendered by Nestopia), $00-$3F
NES = """
666666 002A88 1412A7 3B00A4 5C007E 6E0040 6C0700 561D00
333500 0C4800 005200 004F08 00404D 000000 000000 000000
ADADAD 155FD9 4240FF 7527FE A01ACC B71E7B B53120 994E00
6B6D00 388700 0D9300 008F32 007C8D 000000 000000 000000
FFFFFF 64B0FF 9290FF C676FF F26AFF FF6ECC FF8170 EA9E22
BCBE00 88D800 5CE430 45E082 48CDDE 4F4F4F 000000 000000
FFFFFF C0DFFF D3D2FF E8C8FF FAC2FF FFC4EA FFCCC5 F7D8A5
E4E594 CFEF96 BDF4AB B3F3CC B5EBF2 B8B8B8 000000 000000
""".split()

HW_LEVELS = (0, 52, 87, 116, 144, 172, 206, 255)
LINEAR_LEVELS = tuple(k * 34 for k in range(8))


def nearest(v):
	return min(range(8), key=lambda k: abs(HW_LEVELS[k] - v) + abs(LINEAR_LEVELS[k] - v))


def md_color(rgb):
	r, g, b = (int(rgb[i:i + 2], 16) for i in (0, 2, 4))
	return nearest(b) << 9 | nearest(g) << 5 | nearest(r) << 1


if __name__ == "__main__":
	assert len(NES) == 64
	print("; generated by tools/mkpalette.py")
	for row in range(0, 64, 8):
		vals = ",".join("$%03X" % md_color(c) for c in NES[row:row + 8])
		print("\t\tdc.w %s\t; $%02X-$%02X" % (vals, row, row + 7))
